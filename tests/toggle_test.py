"""ทดสอบสวิตช์ "ตัวชี้วัดอื่น" และหน้าตั้งค่า Data API (โหมดทดลอง): python3 tests/toggle_test.py <out>"""
import asyncio, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import harness as H
from playwright.async_api import async_playwright
OUT = sys.argv[1]; os.makedirs(OUT, exist_ok=True)

async def main():
    H.serve()
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width': 1440, 'height': 900})
        for pat, fn in H.wire(pg): await pg.route(pat, fn)
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(H.BASE + '#map'); await pg.evaluate('localStorage.clear()'); await pg.reload()
        await pg.wait_for_selector('.dist-label', timeout=15000)
        print('public map: other indicators shown =', await pg.locator('#mOther').count())
        await pg.evaluate("API.call('auth.login',{username:'mini',password:'mini1234'}).then(r=>App.setSession(r.token,r.user))"); await pg.wait_for_timeout(400)
        await pg.goto(H.BASE + '#province'); await pg.wait_for_selector('#pItem')
        print('province chart options (off):', await pg.locator('#pItem option').count())
        await pg.goto(H.BASE + '#settings'); await pg.wait_for_selector('[data-set=SHOW_OTHER_INDICATORS]')
        print('mini sees API card:', await pg.locator('#apiCard').count())
        await pg.check('[data-set=SHOW_OTHER_INDICATORS]'); await pg.click('#aSave'); await pg.wait_for_timeout(600)
        await pg.goto(H.BASE + '#map'); await pg.wait_for_selector('.dist-label')
        print('map after enable: other indicators shown =', await pg.locator('#mOther').count())
        await pg.goto(H.BASE + '#province'); await pg.wait_for_selector('#pItem')
        print('province chart options (on):', await pg.locator('#pItem option').count())
        await pg.evaluate("App.logout(true)"); await pg.wait_for_selector('#mLogin')
        print('public map after enable:', await pg.locator('#mOther').count())
        await pg.evaluate("API.call('auth.login',{username:'admin',password:'admin1234'}).then(r=>App.setSession(r.token,r.user))"); await pg.wait_for_timeout(400)
        await pg.goto(H.BASE + '#settings'); await pg.wait_for_selector('#apiCard #keyAdd')
        await pg.click('#keyAdd'); await pg.fill('#keyLabel', 'Dashboard สำนักงานเกษตรจังหวัด'); await pg.click('.modal-f .btn.primary')
        await pg.wait_for_selector('#newKey'); key = await pg.input_value('#newKey'); print('key created:', key[:10] + '…')
        await pg.screenshot(path=f'{OUT}/apikey-modal.png')
        await pg.get_by_role('button', name='เสร็จสิ้น').click(); await pg.wait_for_timeout(400)
        await pg.locator('#apiCard').scroll_into_view_if_needed(); await pg.screenshot(path=f'{OUT}/api-card.png')
        res = await pg.evaluate("(k)=>DemoStoreApi(k)" if False else "(k)=>{const s=AGServer.create(LocalStore.create({key:'kpp-sam-demo-v2'}),AG_ITEMS);return s.api({endpoint:'summary',key:k,round:2}).body}", key)
        print('api summary ok:', res['ok'], [(i['id'], i['cumulative']) for i in res['data']['items']])
        await pg.goto(f'http://localhost:{H.PORT}/docs/api.html'); await pg.wait_for_selector('#exJs')
        await pg.screenshot(path=f'{OUT}/api-docs.png', full_page=True)
        m = await b.new_page(viewport={'width': 390, 'height': 844})
        for pat, fn in H.wire(m): await m.route(pat, fn)
        await m.goto(f'http://localhost:{H.PORT}/docs/api.html'); await m.wait_for_selector('#exJs')
        print('docs mobile scrollWidth', await m.evaluate('document.documentElement.scrollWidth'))
        print('errors', errs)
        await b.close()
asyncio.run(main())
